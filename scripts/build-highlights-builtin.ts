/**
 * Builds the app's BUILT-IN highlight notifications from an approved Highlights .xlsx export:
 *   npx tsx scripts/build-highlights-builtin.ts "<file.xlsx>" "<label>"
 * Writes lib/highlights/builtInConfig.json, which production uses when nothing has been published in the Highlights
 * Admin (owner decision 2026-11-27: highlights are part of the app for every user, like Sleeper's; publishing is only
 * for changing wording without a code update). Refuses a sheet with errors or with nothing Approved.
 */
import fs from "node:fs";
import path from "node:path";
import { buildHighlightDraft } from "../lib/highlights/draft.ts";

const [file, label] = process.argv.slice(2);
if (!file || !label) { console.error('Usage: npx tsx scripts/build-highlights-builtin.ts "<file.xlsx>" "<label>"'); process.exit(1); }
const result = buildHighlightDraft({ bytes: fs.readFileSync(file), fileName: path.basename(file), published: null });
if (!result.ok) { console.error(`Rejected: ${result.error}`); process.exit(1); }
const { draft } = result;
if (draft.report.errors.length) { console.error(`Rejected: ${draft.report.errors.length} errors. Run scripts/check-highlights-xlsx.ts first.`); process.exit(1); }
const approved = draft.config.rules.filter((r) => r.status === "Approved").length;
if (!approved) { console.error("Rejected: nothing is Approved."); process.exit(1); }
const out = path.join(import.meta.dirname, "..", "lib", "highlights", "builtInConfig.json");
fs.writeFileSync(out, `${JSON.stringify({ note: "BUILT-IN highlight notifications (generated by scripts/build-highlights-builtin.ts from the approved sheet). Edit the sheet, not this file.", label, configFingerprint: draft.configFingerprint, config: draft.config }, null, 1)}\n`);
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${approved} approved rules · fingerprint ${draft.configFingerprint}`);
