const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${process.env.DRAFT_TEST_URL || 'http://localhost:3001'}/tournaments/new`, { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.waitForFunction(() => { const form = document.querySelector('main form'); return form && Object.keys(form).some(key => key.startsWith('__reactProps')); });
    const main = page.locator('main').filter({ has: page.getByRole('heading', { name: 'A great tournament starts here.' }) });
    await main.getByRole('button', { name: 'Continue', exact: true }).click();
    await page.locator('main [role=alert]').waitFor();
    await page.getByLabel('Tournament name', { exact: true }).fill('Autumn Invitational');
    await page.getByLabel('Start date', { exact: true }).fill('2026-10-01');
    await page.getByLabel('End date', { exact: true }).fill('2026-10-03');
    const next = async () => { const before = await page.locator('main h2').innerText(); await page.getByRole('button', { name: 'Continue', exact: true }).click(); await page.waitForFunction(previous => document.querySelector('main h2')?.textContent !== previous || document.querySelector('main [role=alert]'), before); };
    await next();
    assert.equal(await page.getByRole('combobox', { name: 'Number of teams', exact: true }).count(), 0);
    await next(); await next(); await next();
    await page.getByRole('combobox', { name: 'Scoring style', exact: true }).waitFor(); assert.equal(await page.getByRole('combobox', { name: 'Scoring style', exact: true }).locator('option').count(), 1);
    await next(); await next();
    await page.getByRole('button', { name: 'Skip for now', exact: true }).click();
    await page.getByRole('button', { name: 'Create draft tournament', exact: true }).click();
    await page.getByRole('heading', { name: 'Tournament Setup — 18% Complete', exact: true }) /* from lib/platform/readiness.ts */.waitFor();
    assert.equal(await page.locator('main article').count(), 11);
    await page.getByRole('button', { name: 'Edit basics', exact: true }).click();
    await page.getByLabel('Tournament name', { exact: true }).fill('Discard this edit');
    await page.getByRole('button', { name: 'Cancel editing', exact: true }).click();
    await page.getByRole('button', { name: 'Edit basics', exact: true }).click();
    assert.equal(await page.getByLabel('Tournament name', { exact: true }).inputValue(), 'Autumn Invitational');
    await next();
    await page.getByRole('combobox', { name: 'Competition type', exact: true }).selectOption('teams');
    await page.getByLabel('Team 1 name', { exact: true }).fill('North');
    await page.getByLabel('Team 2 name', { exact: true }).fill('north');
    await next();
    await page.locator('main [role=alert]').waitFor();
    await page.getByLabel('Team 2 name', { exact: true }).fill('South');
    await next(); await next(); await next();
    await page.getByRole('combobox', { name: 'Scoring style', exact: true }).selectOption('match_play');
    await next();
    for (let i = 1; i <= 3; i++) await page.getByRole('combobox', { name: `Round ${i} format`, exact: true }).selectOption('Singles');
    await next();
    await page.getByLabel('Choose tournament colors now', { exact: true }).check();
    await next();
    await page.getByRole('button', { name: 'Update draft', exact: true }).click();
    await page.getByRole('heading', { name: 'Tournament Setup — 46% Complete', exact: true }).waitFor();
    await page.getByText('View draft configuration', { exact: true }).click();
    const draft = JSON.parse(await page.locator('main pre').innerText());
    assert.equal(draft.teams.length, 2);
    assert.deepEqual(draft.players, []);
    assert.equal(draft.scoring.rules, null);
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download draft JSON', exact: true }).click();
    assert.match((await download).suggestedFilename(), /-draft\.json$/);
    await page.screenshot({ path: 'test-results/tournament-draft-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth), true);
    await page.screenshot({ path: 'test-results/tournament-draft-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Edit basics', exact: true }).click();
    assert.equal(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth), true);
    assert.equal(await page.locator('main form').evaluate(el => el.scrollWidth <= el.clientWidth), true); await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'test-results/tournament-wizard-mobile.png', fullPage: true });
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByLabel('Tournament name', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Tournament name', { exact: true }).inputValue(), '');
    assert.deepEqual(errors, []);
    await page.goto(pathToFileURL(path.resolve('docs/app-workflow.html')).href);
    assert.match(await page.getByRole('region', { name: 'Recent workflow changes' }).innerText(), /Tournament draft wizard/);
    await page.locator('nav.index a').filter({ hasText: '25. Tournament draft' }).click();
    assert.equal(await page.locator('details[open]').count(), 1);
    await page.getByRole('searchbox').fill('tournaments/new');
    assert.equal(await page.locator('#descriptions details:not(.hidden)').filter({ hasText: '25. Tournament draft' }).count(), 1);
    await page.screenshot({ path: 'test-results/tournament-workflow-guide.png', fullPage: true });
    console.log('Passed: individual/team creation, validation, cancel/edit, JSON export, mobile layout, reload reset, workflow changes/navigation/search.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
