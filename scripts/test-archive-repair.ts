import { PGlite } from "@electric-sql/pglite";
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { archiveRepairSql, type ArchiveBackup, type ArchiveRepair } from "./archive-repair-sql";

async function main() {
  const folder = process.argv[2];
  if (!folder) throw new Error("Pass the backup/plan folder generated by repair-historical-archive.ts");
  const backup: ArchiveBackup = JSON.parse(await readFile(`${folder}/backup.json`, "utf8"));
  const { plan, issues }: { plan: ArchiveRepair[]; issues: string[] } = JSON.parse(await readFile(`${folder}/plan.json`, "utf8"));
  assert.deepEqual(issues, []);
  const db = new PGlite();
  try {
    await db.exec(`set timezone = 'UTC'; create role anon; create role authenticated; create role service_role;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create schema storage; create table storage.buckets(id text primary key,name text,public boolean);
      create publication supabase_realtime;`);
    for (const file of ["schema.sql", "career_live_archive.sql", "course_library_tee_setups.sql", "archived_handicap_tees.sql", "round_format_setups.sql"])
      await db.exec(await readFile(`supabase/${file}`, "utf8"));
    for (const [table, rows] of [["archived_scorecard_rounds", backup.rounds], ["archived_scorecard_holes", backup.holes], ["archived_shot_videos", backup.videos], ["round_format_setups", backup.setups]] as const) {
      await db.query(`insert into ${table} select * from jsonb_populate_recordset(null::${table}, $1::jsonb)`, [JSON.stringify(rows)]);
    }
    for (const [table, rows] of [["archived_scorecard_rounds", backup.rounds], ["archived_scorecard_holes", backup.holes], ["archived_shot_videos", backup.videos], ["round_format_setups", backup.setups]] as const) {
      const actual = (await db.query<{ row: Record<string, unknown> }>("select to_jsonb(t) as row from " + table + " t order by " + (table === "round_format_setups" ? "season_year,round" : "id"))).rows.map(row => row.row);
      try { assert.deepEqual(actual, rows); } catch { console.log("Snapshot differs", table, Object.keys(actual[0]), Object.keys(rows[0])); for(const key of Object.keys(rows[0])) if(JSON.stringify(actual[0][key]) !== JSON.stringify(rows[0][key])) console.log(key, actual[0][key], rows[0][key]); throw new Error("Fixture schema/export mismatch"); }
    }
    const sql = archiveRepairSql(backup, plan);
    await db.exec(sql);
    const rows = (await db.query<{ tournament_slug: string; player_slug: string; round: number; course: string; format: string }>("select * from archived_scorecard_rounds")).rows;
    assert.equal(rows.length, 159);
    for (const [slug, count] of [["2024-pinehurst", 47], ["2025-danzante", 40], ["2026-palm-springs", 72]] as const) assert.equal(rows.filter(row => row.tournament_slug === slug).length, count);
    const cade = rows.find(row => row.player_slug === "cade-barone" && row.tournament_slug === "2026-palm-springs" && row.round === 3)!;
    assert.match(cade.course, /classic/i); assert.equal(cade.format, "Fourball");
    await db.exec(sql);
    assert.equal((await db.query<{ count: number }>("select count(*)::int as count from archive_repair_backups")).rows[0].count, 1);
    await db.exec("update archived_scorecard_holes set score = score + 1 where id = (select id from archived_scorecard_holes limit 1)");
    await assert.rejects(db.exec(sql), /Archive changed since backup/);
    await db.exec("rollback");
    assert.equal((await db.query<{ count: number }>("select count(*)::int as count from archived_scorecard_rounds")).rows[0].count, 159);
    console.log("PASS: full backup repaired atomically; 159 rounds, preserved hole details/videos, idempotent rerun, stale plan rejected.");
  } finally { await db.close(); }
}
main().catch(error => { console.error(error instanceof Error ? error.message : error); process.exitCode = 1; });
