const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    fs.mkdirSync("out", { recursive: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1080 } });
    page.setDefaultTimeout(60000);
    await page.goto("http://localhost:3001/dev", { waitUntil: "domcontentloaded" });
    const pages = page.getByRole("complementary", { name: "Pages", exact: true });
    const conditions = page.getByRole("complementary", { name: "Conditionals", exact: true });
    const phone = page.frameLocator("iframe");
    const frame = () => page.frames().find(f => f.parentFrame());
    await phone.getByRole("tab", { name: "Home", exact: true }).waitFor();
    await frame().evaluate(() => window.__storyboardToken = "keep");
    await pages.locator('[data-page-id="trip-Venue"]').click();
    await phone.getByRole("tab", { name: "Venue", exact: true }).waitFor();
    await conditions.getByRole("button", { name: "Mock golf trip data", exact: true }).click();
    await phone.getByRole("heading", { name: "Friends Golf Weekend", exact: true }).waitFor();
    assert.equal(await frame().evaluate(() => window.__storyboardToken), "keep");
    await phone.getByRole("tab", { name: "Info", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-page-id="trip-Info"]').getAttribute("aria-pressed") === "true");
    await conditions.getByText("No conditional states", { exact: true }).waitFor();
    await pages.locator('[data-page-id="trip-Competition"]').click();
    await conditions.getByRole("button", { name: "Scheduled", exact: true }).click();
    assert.equal(await frame().evaluate(() => window.__storyboardToken), "keep");
    await page.getByRole("button", { name: "Golf Trip Onboarding", exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[aria-label="Pages"] button').length === 10);
    assert.equal(await pages.getByRole("button").count(), 10);
    await pages.locator('[data-page-id="trip-setup"]').click();
    await phone.getByRole("link", { name: "Let's go golfing", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-page-id="/golf-trips/new"]').getAttribute("aria-pressed") === "true");
    await conditions.getByText("No conditional states", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Golf Trip Active", exact: true }).click();
    await page.setViewportSize({ width: 560, height: 1080 });
    const boxes = await Promise.all([page.getByRole("complementary", { name: "Development controls" }), pages, conditions, page.locator("iframe")].map(l => l.boundingBox()));
    assert(boxes.every(Boolean));
    assert(boxes[0].x < boxes[1].x && boxes[1].x < boxes[2].x && boxes[2].x < boxes[3].x);
    assert.equal(await page.locator("iframe").getAttribute("width"), "402");
    await page.setViewportSize({ width: 1600, height: 1080 });
    await page.screenshot({ path: "out/dev-storyboard.png" });
    await page.goto("file:///" + process.cwd().replaceAll("\\", "/") + "/docs/app-workflow.html");
    await page.getByLabel("Recent workflow changes").waitFor();
    await page.locator("#search").fill("Simulator storyboard");
    assert(await page.locator("details:not(.hidden)").count() > 0);
    await page.locator("#search").fill("");
    await page.getByRole("heading", { name: /^Simulator storyboard:/, level: 3 }).click();
    assert(await page.locator("details[open]").count() > 0);
    await page.screenshot({ path: "out/dev-storyboard-workflow.png" });
    console.log("PASS: storyboard columns, onboarding inventory, bidirectional navigation, conditional updates without reload, narrow layout, workflow changes/navigation/search");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
